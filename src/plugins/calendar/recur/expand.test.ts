import { describe, it, expect } from 'vitest';
import { expand, MAX_RESULTS } from './expand';

const W = ['2000-01-01', '2100-01-01'] as const;

describe('expand', () => {
    it('매일 · interval · 반열림 경계', () => {
        expect(expand({ freq: 'daily' }, '2026-03-01', '2026-03-02', '2026-03-04')).toEqual(['2026-03-02', '2026-03-03']);
        expect(expand({ freq: 'daily', interval: 3 }, '2026-03-01', '2026-03-01', '2026-03-11')).toEqual(['2026-03-01', '2026-03-04', '2026-03-07', '2026-03-10']);
    });
    it('시각 일정 — 시각 유지, 같은 날 to 경계', () => {
        const r = expand({ freq: 'daily' }, '2026-03-01T09:30', '2026-03-01T09:30', '2026-03-03T09:30');
        expect(r).toEqual(['2026-03-01T09:30', '2026-03-02T09:30']);
        expect(expand({ freq: 'daily' }, '2026-03-01T09:30', '2026-03-02T09:31', '2026-03-04T00:00')).toEqual(['2026-03-03T09:30']);
    });
    it('종일 일정이 시각 범위에도 잡힌다', () => {
        expect(expand({ freq: 'daily' }, '2026-03-01', '2026-03-02T00:00', '2026-03-03T00:00')).toEqual(['2026-03-02']);
    });
    it('매주 요일들(2026-03-02 = 월) · 격주', () => {
        expect(expand({ freq: 'weekly', weekdays: [1, 3] }, '2026-03-02', '2026-03-01', '2026-03-16'))
            .toEqual(['2026-03-02', '2026-03-04', '2026-03-09', '2026-03-11']);
        expect(expand({ freq: 'weekly', interval: 2 }, '2026-03-02', ...['2026-03-01', '2026-04-01'] as const))
            .toEqual(['2026-03-02', '2026-03-16', '2026-03-30']);
    });
    it('매주 — 시작일 이전 요일은 안 나온다', () => {
        expect(expand({ freq: 'weekly', weekdays: [1, 5] }, '2026-03-04', '2026-03-01', '2026-03-10')).toEqual(['2026-03-06', '2026-03-09']);
    });
    it('매월 31일 — 없는 달은 건너뜀', () => {
        expect(expand({ freq: 'monthly' }, '2026-01-31', '2026-01-01', '2026-06-01'))
            .toEqual(['2026-01-31', '2026-03-31', '2026-05-31']);
    });
    it('매월 말일(-1)', () => {
        expect(expand({ freq: 'monthly', monthDay: -1 }, '2026-01-31', '2026-01-01', '2026-04-01'))
            .toEqual(['2026-01-31', '2026-02-28', '2026-03-31']);
    });
    it('N째 요일 · 5째 요일은 없는 달 건너뜀 · 마지막 요일', () => {
        // 2026-03-10 = 둘째 화
        expect(expand({ freq: 'monthly', nth: { n: 2, weekday: 2 } }, '2026-03-10', '2026-03-01', '2026-06-01'))
            .toEqual(['2026-03-10', '2026-04-14', '2026-05-12']);
        // 5째 금: 2026-01-30 · 2026-05-29 · (2~4월은 4번뿐)
        expect(expand({ freq: 'monthly', nth: { n: 5, weekday: 5 } }, '2026-01-30', '2026-01-01', '2026-07-01'))
            .toEqual(['2026-01-30', '2026-05-29']);
        expect(expand({ freq: 'monthly', nth: { n: -1, weekday: 5 } }, '2026-01-30', '2026-01-01', '2026-04-01'))
            .toEqual(['2026-01-30', '2026-02-27', '2026-03-27']);
    });
    it('매년 · 윤년 2/29 는 윤년에만', () => {
        expect(expand({ freq: 'yearly' }, '2024-02-29', ...W).slice(0, 4)).toEqual(['2024-02-29', '2028-02-29', '2032-02-29', '2036-02-29']);
        expect(expand({ freq: 'yearly', interval: 2 }, '2026-05-05', '2026-01-01', '2032-01-01')).toEqual(['2026-05-05', '2028-05-05', '2030-05-05']);
    });
    it('count — 시작 회차 포함, 범위 앞 회차도 센다', () => {
        expect(expand({ freq: 'daily', count: 3 }, '2026-03-01', ...W)).toEqual(['2026-03-01', '2026-03-02', '2026-03-03']);
        expect(expand({ freq: 'daily', count: 5 }, '2026-03-01', '2026-03-04', '2026-04-01')).toEqual(['2026-03-04', '2026-03-05']);
    });
    it('until — 그 날 포함', () => {
        expect(expand({ freq: 'daily', until: '2026-03-03' }, '2026-03-01T10:00', ...W)).toEqual(['2026-03-01T10:00', '2026-03-02T10:00', '2026-03-03T10:00']);
    });
    it('exdates — 날짜 전체 또는 시각 전체, count 는 줄지 않는다', () => {
        expect(expand({ freq: 'daily', count: 3, exdates: ['2026-03-02'] }, '2026-03-01', ...W)).toEqual(['2026-03-01', '2026-03-03']);
        expect(expand({ freq: 'daily', count: 2, exdates: ['2026-03-01T09:00'] }, '2026-03-01T09:00', ...W)).toEqual(['2026-03-02T09:00']);
    });
    it('무한 규칙도 범위·상한으로 끊긴다', () => {
        expect(expand({ freq: 'daily' }, '2026-01-01', '2026-01-01', '2026-02-01')).toHaveLength(31);
        expect(expand({ freq: 'daily' }, '2000-01-01', '2000-01-01', '9000-01-01')).toHaveLength(MAX_RESULTS);
    });
    it('영영 안 맞는 규칙은 멈춘다', () => {
        expect(expand({ freq: 'yearly' }, '2026-02-30', ...W)).toEqual([]);
        expect(expand({ freq: 'monthly', monthDay: 31, interval: 12 }, '2026-02-10', ...W)).toEqual([]);
    });
});
